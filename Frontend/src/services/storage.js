export function loadPortalData() {
  try {
    const raw = localStorage.getItem(STORAGE_KEYS.DATA);
    if (!raw) {
      const seed = getInitialData();
      localStorage.setItem(STORAGE_KEYS.DATA, JSON.stringify(seed));
      return seed;
    }
    const parsed = JSON.parse(raw);
    const seed = getInitialData();
    return {
      companies: parsed.companies || seed.companies,
      jobs: parsed.jobs || seed.jobs,
      students: parsed.students || seed.students,
      admins: parsed.admins || seed.admins,
      applications: parsed.applications || seed.applications,
      interviews: parsed.interviews || seed.interviews,
      studentNotifications: parsed.studentNotifications || seed.studentNotifications,
      adminNotifications: parsed.adminNotifications || seed.adminNotifications,
      activities: parsed.activities || seed.activities,
    };
  } catch {
    return getInitialData();
  }
}

