export function checkJobEligibility(student, job) {
  if (!student || !job) {
    return { eligible: false, reasons: ['Missing student or job profile'] };
  }
  const reasons = [];
  const cgpa = Number(student.cgpa) || 0;
  const backlogs = Number(student.backlogs) || 0;

  if (cgpa < Number(job.minCGPA)) {
    reasons.push(`Minimum CGPA ${job.minCGPA} required (Your CGPA: ${cgpa})`);
  }
  if (
    Array.isArray(job.eligibleBranches) &&
    job.eligibleBranches.length > 0 &&
    !job.eligibleBranches.includes('All') &&
    !job.eligibleBranches.includes(student.department)
  ) {
    reasons.push(`Department ${student.department} is not in eligible branches`);
  }
  if (backlogs > Number(job.allowedBacklogs)) {
    reasons.push(`Max ${job.allowedBacklogs} backlog(s) permitted (Yours: ${backlogs})`);
  }
  if (job.status !== 'Open') {
    reasons.push('Applications for this drive are closed');
  }

  return {
    eligible: reasons.length === 0,
    reasons,
  };
}
